package logger

import (
	"log"
	"sync/atomic"

	"go.uber.org/zap"
	"go.uber.org/zap/zapcore"

	"github.com/klinoklaz/greenhouse/config"
	"github.com/klinoklaz/greenhouse/util"
)

var l atomic.Pointer[zap.Logger]

func Get() *zap.Logger {
	return l.Load()
}

func Init() {
	zc := &zap.Config{
		DisableCaller:     true,
		DisableStacktrace: true,
		OutputPaths:       []string{config.Log().Location},
	}
	if config.Log().UseJSON {
		zc.Encoding = "json"
		zc.EncoderConfig = zap.NewProductionEncoderConfig()
	} else {
		zc.Encoding = "console"
		zc.EncoderConfig = zap.NewDevelopmentEncoderConfig()
	}
	zc.EncoderConfig.EncodeTime = zapcore.RFC3339TimeEncoder
	zc.Level.UnmarshalText([]byte(config.Log().Level))
	if zl, err := zc.Build(); err == nil {
		l.Store(zl)
	} else {
		if zl = Get(); zl == nil {
			zl = zap.Must(zap.NewDevelopment())
			l.Store(zl)
		}
		zl.Error("logger initialization failed", zap.Error(err))
	}
}

type interceptor util.Void

func (i interceptor) Write(b []byte) (int, error) {
	if Get() == nil {
		return 0, nil
	}
	Get().Debug("rogue message from external log source",
		zap.ByteString("text", b))
	return len(b), nil
}

func init() {
	// intercept logs generated by httputil package
	log.SetOutput(interceptor{})
}
